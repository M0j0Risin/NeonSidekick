"""Generates the C# data tables that come from SearXNG's, Babel's and Python's own data.

usage: generate_tables.py <searxng_checkout> <src_dir>
needs: SearXNG's requirements.txt installed in the running Python
"""
import html.entities
import json
import os
import sys
import warnings

SEARXNG, SRC = sys.argv[1:3]
sys.path.insert(0, SEARXNG)
os.environ.setdefault("SEARXNG_SECRET", "table-generation-only")
warnings.simplefilter("ignore")

import babel  # noqa: E402
import babel.core  # noqa: E402
import babel.languages  # noqa: E402
import babel.localedata  # noqa: E402

with open(os.path.join(SEARXNG, "searx", "data", "engine_traits.json"), encoding="utf8") as f:
    TRAITS = json.load(f)


def literal(text):
    out = []
    for ch in text:
        code = ord(ch)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= code < 0x7F:
            out.append(ch)
        elif code <= 0xFFFF:
            out.append(f"\\u{code:04X}")
        else:
            out.append(f"\\U{code:08X}")
    return '"' + "".join(out) + '"'


def dictionary(name, summary, items):
    lines = [f"    /// <summary>{summary}</summary>"]
    lines.append(f"    internal static readonly IReadOnlyDictionary<string, string> {name} = new Dictionary<string, string>(StringComparer.Ordinal)")
    lines.append("    {")
    lines += [f"        [{literal(k)}] = {literal(v)}," for k, v in items]
    lines.append("    };")
    return lines


def lists(name, summary, items):
    lines = [f"    /// <summary>{summary}</summary>"]
    lines.append(f"    internal static readonly IReadOnlyDictionary<string, string[]> {name} = new Dictionary<string, string[]>(StringComparer.Ordinal)")
    lines.append("    {")
    lines += [f"        [{literal(k)}] = [{', '.join(literal(v) for v in values)}]," for k, values in items]
    lines.append("    };")
    return lines


def write(path, namespace, class_summary, class_name, blocks):
    lines = [
        "// SPDX-License-Identifier: AGPL-3.0-or-later",
        "// <auto-generated>Generated by tools/searxng/generate_tables.py. Don't edit by hand.</auto-generated>",
        "",
        f"namespace {namespace};",
        "",
        f"/// <summary>{class_summary}</summary>",
        f"internal static class {class_name}",
        "{",
    ]
    for i, block in enumerate(blocks):
        if i:
            lines.append("")
        lines += block
    lines.append("}")
    full = os.path.join(SRC, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def engine_table(engine, key, summary, name):
    return dictionary(name, summary, sorted(TRAITS[engine][key].items()))


# --- Babel --------------------------------------------------------------------------------------------------------------------
# What Locale.parse makes of a tag. Babel only accepts a language and territory it can resolve, so ar-AD fails while en-DE,
# zh-MY (to zh-Hans-MY) and ar-ZZ (to ar-EG) succeed. get_engine_locale treats a failure as the bare language.
identifiers = [i.replace("_", "-") for i in babel.localedata.locale_identifiers()]
languages = {i for i in identifiers if "-" not in i} | set(babel.core.get_global("language_aliases"))
territory_languages = babel.core.get_global("territory_languages")
codes = set(territory_languages) | set(babel.core.get_global("territory_aliases")) | {"ZZ"}
codes = sorted(c for c in codes if len(c) == 2 and c.isalpha())
# The names engines use, such as Wikipedia's zh-classical, which Babel reads as another language.
engine_tags = {t for engine in ("bing", "brave", "startpage", "wikipedia") for key in ("regions", "languages") for t in TRAITS[engine][key] if "_" not in t}
resolved = {}
for tag in sorted(set(identifiers) | languages | engine_tags | {f"{language}-{code}" for language in languages for code in codes}):
    try:
        locale = babel.Locale.parse(tag, sep="-")
    except (babel.core.UnknownLocaleError, ValueError):
        continue
    resolved[tag] = "-".join(part for part in (locale.language, locale.script, locale.territory) if part)

officials = sorted((t, babel.languages.get_official_languages(t, de_facto=True)) for t in territory_languages)
officials = [(t, values) for t, values in officials if values]

# Each language's territories where it has official status, most of the population first.
by_language = {}
for territory, spoken in territory_languages.items():
    for language, info in spoken.items():
        if info.get("official_status") is not None:
            by_language.setdefault(language, []).append((territory, info["population_percent"]))
territories = [(k, [t for t, _ in sorted(v, key=lambda item: item[1], reverse=True)]) for k, v in sorted(by_language.items())]

write(
    "Locales/LocaleData.cs",
    "SearXNG.Net.Locales",
    f"The parts of Babel {babel.__version__}'s data that SearXNG's <c>get_engine_locale</c> reads.",
    "LocaleData",
    [
        dictionary("Resolved", "What <c>Locale.parse</c> makes of a tag it accepts, as language, script and territory.", sorted(resolved.items())),
        lists("OfficialLanguages", "A territory's official languages, in Babel's order.", officials),
        lists("LanguageTerritories", "The territories where a language is official, most of the population first.", territories),
    ],
)

# --- Engines ------------------------------------------------------------------------------------------------------------------
write(
    "Engines/BingRegions.cs",
    "SearXNG.Net.Engines",
    "Bing's markets, from SearXNG's <c>engine_traits.json</c>.",
    "BingRegions",
    [engine_table("bing", "regions", "The locales Bing has a market for.", "Table")],
)
write(
    "Engines/BraveLocales.cs",
    "SearXNG.Net.Engines",
    "Brave's locales, from SearXNG's <c>engine_traits.json</c>.",
    "BraveLocales",
    [
        engine_table("brave", "regions", "The locales Brave has a country for.", "Regions"),
        dictionary("InterfaceLanguages", "The locales Brave has an interface language for.", sorted(TRAITS["brave"]["custom"]["ui_lang"].items())),
    ],
)
write(
    "Engines/StartpageLocales.cs",
    "SearXNG.Net.Engines",
    "Startpage's locales, from SearXNG's <c>engine_traits.json</c>.",
    "StartpageLocales",
    [
        engine_table("startpage", "regions", "The locales Startpage has a region for.", "Regions"),
        engine_table("startpage", "languages", "The locales Startpage has a language for.", "Languages"),
    ],
)
write(
    "Engines/WikipediaLocales.cs",
    "SearXNG.Net.Engines",
    "Wikipedia's locales, from SearXNG's <c>engine_traits.json</c>.",
    "WikipediaLocales",
    [
        engine_table("wikipedia", "regions", "The locales that pick a language variant.", "Regions"),
        engine_table("wikipedia", "languages", "The locales Wikipedia has a language for.", "Languages"),
        dictionary("Hosts", "Each language's wiki.", sorted(TRAITS["wikipedia"]["custom"]["wiki_netloc"].items())),
    ],
)

write(
    "Html/HtmlEntityTable.cs",
    "SearXNG.Net.Html",
    "The HTML5 named character references, from Python's <c>html.entities.html5</c>. Names without a semicolon are the legacy forms.",
    "HtmlEntityTable",
    [dictionary("Names", "Each reference's name, without the ampersand, and its text.", sorted(html.entities.html5.items()))],
)
print("resolved", len(resolved), "official", len(officials), "language territories", len(territories), "entities", len(html.entities.html5))
